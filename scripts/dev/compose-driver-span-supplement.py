#!/usr/bin/env python3
"""Offline DSP supplement: preserve an independently verified base cache byte for byte.

This is not a new full shader-chain build or a deployment tool. Proof eligibility
is inherited only from a pinned, complete original deploy verifier report whose
five fingerprinted artifacts are identical to the base cache. No SPIR-V analyzer,
translator, Android command, or runtime code is run here.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'dm/gfx/tools'))
import dmsh_driver_keys as driver
import dmsh_uniform_predicates

MANIFEST = '_driver_span_supplement.json'


def require(value, message):
    if not value:
        raise ValueError(message)


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def record(path):
    path = Path(path).resolve()
    return {'path': str(path), 'sha256': sha(path), 'bytes': path.stat().st_size}


def no_duplicates(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, 'duplicate JSON member: '+key)
        result[key] = value
    return result


def read_json(path):
    return json.loads(Path(path).read_text(), object_pairs_hook=no_duplicates)


def pinned_json(path, digest):
    require(re.fullmatch('[0-9a-f]{64}', digest or ''), 'expected SHA256 required')
    require(Path(path).is_file() and not Path(path).is_symlink(), 'invalid receipt file')
    require(sha(path) == digest, 'receipt SHA256 mismatch: '+str(path))
    return read_json(path)


def inventory(cache):
    result = {}
    for path in sorted(cache.iterdir()):
        require(path.is_file() and not path.is_symlink(), 'directory/link in cache: '+str(path))
        result[path.name] = {'sha256': sha(path), 'bytes': path.stat().st_size}
    return result


def inventory_digest(items):
    return hashlib.sha256(json.dumps(items, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def verified_cache(cache, receipt, total):
    require(cache.is_dir() and not cache.is_symlink(), 'invalid shader cache')
    require(isinstance(receipt, dict), 'source receipt must be an object')
    chain = receipt.get('chain')
    require(isinstance(chain, str) and re.fullmatch('[0-9a-f]{12}', chain), 'invalid source chain')
    require(cache.name == 'vk-'+chain and (cache/'.chain').read_text().strip() == chain,
            'cache/source-chain mismatch')
    require(receipt.get('original_proofs_unchanged') is True and
            receipt.get('validated_game_and_builtin_shaders') == total,
            'incomplete original shader verification')
    artifacts = receipt.get('artifacts')
    require(isinstance(artifacts, dict) and artifacts, 'missing complete artifact map')
    for name, entry in artifacts.items():
        require(Path(name).name == name and name not in ('', '.', '..') and
                isinstance(entry, dict) and set(entry) == {'sha256', 'bytes'} and
                isinstance(entry['sha256'], str) and re.fullmatch('[0-9a-f]{64}', entry['sha256']) and
                type(entry['bytes']) is int and entry['bytes'] >= 0, 'invalid artifact record')
    actual = inventory(cache)
    require(actual == artifacts, 'source inventory/hash mismatch: '+str(cache))
    manifest = read_json(cache/'_vk_manifest.json')
    require(isinstance(manifest, dict) and manifest.get('chain') == chain and manifest.get('expected') == total and
            manifest.get('validated') == total and manifest.get('target') == 'vulkan1.1',
            'incomplete source build manifest')
    builds = read_json(cache/'_vk_build.json')
    keys = {Path(name).stem for name in artifacts if re.fullmatch(r'[0-9a-f]{16}\.spv', name)}
    require(len(keys) == total and keys == {Path(n).stem for n in artifacts
            if re.fullmatch(r'[0-9a-f]{16}\.meta', n)}, 'shader/metadata key set mismatch')
    require(isinstance(builds, list) and len(builds) == total and
            all(isinstance(r, dict) and r.get('st') == 'ok' for r in builds) and
            {r['key'] for r in builds} == keys, 'incomplete source build results')
    return actual, keys


def verify_wire(blobs, reflection, payload):
    """Check original DSP1 serialization; never derive a new SPIR-V read bound.

    The supplied bound was independently regenerated by the pinned full verifier.
    This step only transfers that proof across an identical immutable closure.
    """
    stage, descriptor_set, bindings = driver.metadata(blobs['meta'])
    require(0 <= descriptor_set < 6 and len(payload) == driver.SPAN_BYTES, 'DSP shape')
    declaration = reflection.get('driver_spans')
    require(isinstance(declaration, dict) and set(declaration) == {'sha256', 'proof'} and
            declaration['sha256'] == hashlib.sha256(payload).hexdigest(), 'DSP declaration/hash mismatch')
    proof = declaration['proof']
    require(isinstance(proof, dict) and set(proof) == {'0', '2'}, 'DSP proof slots')
    wire = bytearray(struct.pack('<4I', driver.SPAN_MAGIC, 1, stage, descriptor_set) + driver.fingerprint(blobs))
    for slot in (0, 2):
        entry = proof[str(slot)]
        require(isinstance(entry, dict) and set(entry) == {'binding', 'max_read_end', 'reason'} and
                isinstance(entry['reason'], str), 'DSP slot proof')
        binding, end = entry['binding'], entry['max_read_end']
        matches = [b for b in bindings if b[0] == 1 and b[2] == slot]
        actual_binding = matches[0][1] if len(matches) == 1 else 0xffffffff
        require(type(binding) is int and 0 <= binding <= 0xffffffff and binding == actual_binding and
                type(end) is int and 0 <= end <= 65536 and end % 4 == 0, 'DSP binding/end')
        require(end == 65536 or (len(matches) == 1 and matches[0][5] == 1 and binding < 128),
                'DSP compact range without scalar descriptor binding')
        wire += struct.pack('<2I', binding, end)
    wire += hashlib.sha256(wire).digest()
    require(bytes(wire) == payload, 'DSP wire/fingerprint/digest mismatch')
    return driver.fingerprint(blobs).hex()


def producer():
    return {'git_revision': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
            'sources': [record(p) for p in (Path(__file__), Path(driver.__file__),
                                           Path(dmsh_uniform_predicates.__file__))],
            'python': sys.version.split()[0]}


def verify_sources(args, total=6931, game_count=6927):
    old = pinned_json(args.baseline_receipt, args.baseline_receipt_sha256)
    proof = pinned_json(args.proof_receipt, args.proof_receipt_sha256)
    ready = pinned_json(args.proof_ready, args.proof_ready_sha256)
    inputs = pinned_json(args.proof_build_inputs, args.proof_build_inputs_sha256)
    require(isinstance(ready, dict) and isinstance(inputs, dict), 'proof Ready/build-inputs must be objects')
    base, current = args.baseline_cache.resolve(), args.proof_cache.resolve()
    old_files, keys = verified_cache(base, old, total)
    proof_files, proof_keys = verified_cache(current, proof, total)
    require(keys == proof_keys and old.get('deployed') is True and
            old.get('phone_verified_files') == len(old_files), 'missing original complete deployment receipt')
    require(proof.get('deployed') is False and proof.get('baseline_spirv_identical') is True,
            'proof source lacks complete independent baseline verification')
    require(ready.get('chain') == proof['chain'] and Path(ready.get('cache', '')).resolve() == current,
            'proof Ready/source-chain mismatch')
    for key, path in [('original_deploy_dryverify', args.proof_receipt), ('build_inputs', args.proof_build_inputs)]:
        declared = ready.get(key)
        require(isinstance(declared, dict) and declared.get('sha256') == sha(path) and
                declared.get('bytes') == Path(path).stat().st_size, 'proof Ready receipt mismatch: '+key)
    evidence = {}
    for key in ('translator_tools', 'producer_source_archive'):
        item = ready.get(key)
        require(isinstance(item, dict) and record(item['path']) == item, 'proof producer evidence changed: '+key)
        evidence[key] = item
    # The imported wire/fingerprint implementation must be the one qualified by
    # the full proof producer, even if a different runtime tree consumes it.
    for module in (driver, dmsh_uniform_predicates):
        relative = Path(module.__file__).resolve().relative_to(ROOT).as_posix()
        rows = [r for r in inputs.get('sources', []) if r['path'].endswith('/'+relative)]
        require(len(rows) == 1 and rows[0]['sha256'] == sha(module.__file__), 'proof implementation changed: '+relative)
    games = {Path(n).stem for n in old_files if re.fullmatch(r'[0-9a-f]{16}\.json', n)}
    require(len(games) == game_count and games <= keys and games == {
        Path(n).stem for n in proof_files if re.fullmatch(r'[0-9a-f]{16}\.json', n)}, 'game reflection key set mismatch')
    require(not any(n.endswith('.dspan') for n in old_files), 'base already contains a supplement')
    require({Path(n).stem for n in proof_files if n.endswith('.dspan')} == games, 'DSP key set mismatch')
    additions = {}
    for key in sorted(keys):
        blobs = {}
        for suffix in driver.SUFFIXES:
            name = key+'.'+suffix
            require((name in old_files) == (name in proof_files), 'five-artifact presence mismatch: '+name)
            if name in old_files:
                require(old_files[name] == proof_files[name], 'five-artifact bytes mismatch: '+name)
                blobs[suffix] = (base/name).read_bytes()
        if key not in games:
            continue
        payload = (current/(key+'.dspan')).read_bytes()
        fingerprint = verify_wire(blobs, read_json(current/(key+'.json')), payload)
        additions[key+'.dspan'] = dict(proof_files[key+'.dspan'], fingerprint=fingerprint)
    desired = dict(old_files, **{name: {k: value[k] for k in ('sha256', 'bytes')}
                                for name, value in additions.items()})
    manifest = {'schema': 1, 'kind': 'driver-uniform-span-supplement',
                'base_chain': old['chain'], 'proof_chain': proof['chain'],
                'baseline_receipt': record(args.baseline_receipt),
                'proof_receipt': record(args.proof_receipt), 'proof_ready': record(args.proof_ready),
                'proof_build_inputs': record(args.proof_build_inputs), 'proof_producer_evidence': evidence,
                'producer': producer(), 'base_files': len(old_files), 'added_files': len(additions),
                'added_DSP_bytes': sum(v['bytes'] for v in additions.values()),
                'base_inventory_sha256': inventory_digest(old_files),
                'composed_inventory_excluding_this_manifest_sha256': inventory_digest(desired),
                'dspan_artifacts': additions,
                'contract': 'Keep every base artifact including .chain/JSON/DPL unchanged. Only append DSP1 and this manifest.',
                'proof_scope': 'Full original verifier regenerated proofs from actual modules; all five immutable artifact bytes match base. No new SPIR-V analysis or full-chain relabeling.'}
    return base, current, desired, manifest


def verify_output(output, desired, manifest):
    require(output.is_dir() and not output.is_symlink(), 'missing composed output')
    require(read_json(output/MANIFEST) == manifest, 'supplement manifest changed')
    expected = dict(desired, **{MANIFEST: {'sha256': sha(output/MANIFEST), 'bytes': (output/MANIFEST).stat().st_size}})
    require(inventory(output) == expected, 'composed inventory/hash mismatch')
    return expected


def compose(args, total=6931, game_count=6927):
    base, proof, desired, manifest = verify_sources(args, total, game_count)
    output = args.output.resolve()
    require(not any(output.is_relative_to(p) or p.is_relative_to(output) for p in (base, proof)),
            'output overlaps a source cache')
    if not args.verify_only:
        require(not output.exists(), 'output already exists')
        output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='.driver-span-compose-', dir=output.parent) as temporary:
            incoming = Path(temporary)/'cache'; incoming.mkdir()
            for name in desired:
                shutil.copyfile((proof if name.endswith('.dspan') else base)/name, incoming/name)
            (incoming/MANIFEST).write_text(json.dumps(manifest, sort_keys=True, indent=1)+'\n')
            verify_output(incoming, desired, manifest)
            incoming.rename(output)
    artifacts = verify_output(output, desired, manifest)
    return {'schema': 1, 'kind': 'verified-driver-uniform-span-supplement', 'output': str(output),
            'verify_only': args.verify_only, 'base_chain': manifest['base_chain'], 'proof_chain': manifest['proof_chain'],
            'baseline_receipt': manifest['baseline_receipt'], 'proof_receipt': manifest['proof_receipt'],
            'supplement_manifest': record(output/MANIFEST), 'artifacts': artifacts,
            'base_artifacts_preserved_byte_exact': manifest['base_files'],
            'DSP_files_added': manifest['added_files'], 'DSP_bytes_added': manifest['added_DSP_bytes'],
            'manifest_bytes_added': (output/MANIFEST).stat().st_size,
            'deployed': False, 'game_binary_modified': False, 'SPIRV_analysis_rerun': False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('baseline-cache', 'baseline-receipt', 'proof-cache', 'proof-receipt',
                 'proof-ready', 'proof-build-inputs', 'output', 'report'):
        parser.add_argument('--'+name, type=Path, required=True)
    for name in ('baseline-receipt', 'proof-receipt', 'proof-ready', 'proof-build-inputs'):
        parser.add_argument('--'+name+'-sha256', required=True)
    parser.add_argument('--verify-only', action='store_true')
    args = parser.parse_args()
    require(not args.report.exists(), 'report already exists; preserve the original receipt')
    for source in (args.baseline_cache, args.proof_cache, args.output):
        require(not args.report.resolve().is_relative_to(source.resolve()), 'report must be outside shader caches')
    result = compose(args)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(result, sort_keys=True, indent=1)+'\n')
    print(json.dumps({k: v for k, v in result.items() if k != 'artifacts'}, sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError, OSError, struct.error) as error:
        raise SystemExit(str(error)) from error
